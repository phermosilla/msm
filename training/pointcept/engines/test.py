class KNNSemSegTester(TesterBase):
    """KNNSemSegTester
    for large outdoor point cloud
    """

    def __init__(self, cfg, 
                 model=None, 
                 test_loader=None, 
                 prototype_method = "farthest",
                 verbose=False) -> None:
        
        super(KNNSemSegTester, self).__init__(
            cfg, model, test_loader, verbose)
        
        self.k = cfg.test.k
        self.num_prototypes = cfg.test.prototypes
        self.num_prototypes_scene = cfg.test.prototypes_scene
        self.prototype_method = prototype_method

        self.prototypes = [None for _ in range(cfg.data.num_classes)]

        self.train_loader = self.build_train_loader()


    def build_train_loader(self):
        train_dataset = build_dataset(self.cfg.data.train)
        train_loader = torch.utils.data.DataLoader(
            train_dataset,
            batch_size=1,
            shuffle=False,
            num_workers=1,
            pin_memory=True,
            sampler=None,
            collate_fn=self.__class__.collate_fn,
        )
        return train_loader
    
    
    def farthest_point_sampling(self, p_pts, p_num_pts, return_indices = False):
        indices = [0]
        cur_point = p_pts[indices[0]]
        dist = torch.linalg.norm(p_pts - cur_point, dim = 1)
        while len(indices) < p_num_pts:
            curr_ind = torch.argmax(dist)
            indices.append(curr_ind)
            cur_point = p_pts[curr_ind]
            dist = torch.amin(torch.cat((dist.reshape(-1, 1), \
                torch.linalg.norm(p_pts-cur_point, dim = 1).reshape(-1, 1)), 1), 1) 
        if not return_indices:    
            return p_pts[indices, :]
        else:
            return p_pts[indices, :], indices

    
    def kmeans(self, p_pts, p_num_pts, return_indices = False):
        kmeans = KMeans(n_clusters=p_num_pts, 
            random_state=0, n_init="auto").fit(p_pts.cpu().numpy())
        if not return_indices:
            return torch.from_numpy(kmeans.cluster_centers_).to(p_pts.dtype).to(p_pts.device)
        else:
            return torch.from_numpy(kmeans.cluster_centers_).to(p_pts.dtype).to(p_pts.device), \
                torch.from_numpy(kmeans.labels_).to(torch.int32).to(p_pts.device)
    
    
    def update_prototypes(self, new_features, new_segment):
        for cur_cls in range(self.cfg.data.num_classes):
            mask = new_segment == cur_cls
            if torch.sum(mask).item() > 0:
                cur_pts = new_features[mask]
                if cur_pts.shape[0] > self.num_prototypes_scene and self.num_prototypes_scene != 0:
                    if self.prototype_method == "farthest":
                        cur_pts = self.farthest_point_sampling(cur_pts, self.num_prototypes_scene)
                    elif self.prototype_method == "kmeans":
                        cur_pts = self.kmeans(cur_pts, self.num_prototypes_scene)
                if self.prototypes[cur_cls] is None:
                    self.prototypes[cur_cls] = [cur_pts]
                else:
                    self.prototypes[cur_cls].append(cur_pts)


    def find_on_train(self, test_feats, train_feats, train_probs, device):

        block_test = 10000
        feat_size = train_feats.shape[-1]
        
        test_iter = 0
        final_pred = torch.zeros((test_feats.shape[0], train_probs.shape[-1]), 
                                dtype=torch.int32).to(device)
        while test_iter < test_feats.shape[0]:
            test_end_iter = test_iter + block_test
            if test_end_iter >= test_feats.shape[0]:
                test_end_iter = test_feats.shape[0]

            cur_test_feats = test_feats[test_iter:test_end_iter]

            distance_feats = torch.cdist(
                cur_test_feats.reshape((1, -1, feat_size)), 
                train_feats.reshape((1, -1, feat_size)))\
                .reshape((cur_test_feats.shape[0], train_feats.shape[0]))
            cur_min_idxs = torch.topk(-distance_feats, self.k, -1)[1]
            
            probs = train_probs[cur_min_idxs.reshape((-1,)), :].to(torch.float32)
            probs = torch.mean(probs.reshape((-1, self.k, train_probs.shape[-1])), 1)
            
            final_pred[test_iter:test_end_iter, :] = probs
            test_iter = test_end_iter

        return final_pred


