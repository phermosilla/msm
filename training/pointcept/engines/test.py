class TTTKDSemSegTester(TesterBase):
    """TTTKDSemSegTester
    for large outdoor point cloud
    """

    def __init__(self, cfg, 
                 model=None, 
                 test_loader=None, 
                 verbose=False) -> None:
        self.num_ttt_steps = cfg.test.num_ttt_steps
        self.online = cfg.test.online
        self.scene_online = cfg.test.scene_online
        self.num_updates_scene = cfg.test.num_updates_scene
        self.optimizer = cfg.test.optimizer
        super(TTTKDSemSegTester, self).__init__(cfg, model, test_loader, verbose)

    def test(self):
        
        assert self.test_loader.batch_size == 1
        logger = get_root_logger()
        logger.info(">>>>>>>>>>>>>>>> Start Evaluation >>>>>>>>>>>>>>>>")

        batch_time = AverageMeter()
        intersection_meter = AverageMeter()
        union_meter = AverageMeter()
        target_meter = AverageMeter()
        self.model.eval()
        optimizer = build_optimizer(self.optimizer, self.model.get_ttt_opt_model())
        scaler = torch.cuda.amp.GradScaler() if self.cfg.enable_amp else None

        init_parameters = copy.deepcopy(self.model).state_dict()

        save_path = os.path.join(self.cfg.save_path, "result")
        make_dirs(save_path)
        # create submit folder only on main process
        if (
            self.cfg.data.test.type == "ScanNetDataset"
            or self.cfg.data.test.type == "ScanNet200Dataset"
        ) and comm.is_main_process():
            make_dirs(os.path.join(save_path, "submit"))
        elif (
            self.cfg.data.test.type == "SemanticKITTIDataset" and comm.is_main_process()
        ):
            make_dirs(os.path.join(save_path, "submit"))
        elif self.cfg.data.test.type == "NuScenesDataset" and comm.is_main_process():
            import json

            make_dirs(os.path.join(save_path, "submit", "lidarseg", "test"))
            make_dirs(os.path.join(save_path, "submit", "test"))
            submission = dict(
                meta=dict(
                    use_camera=False,
                    use_lidar=True,
                    use_radar=False,
                    use_map=False,
                    use_external=False,
                )
            )
            with open(
                os.path.join(save_path, "submit", "test", "submission.json"), "w"
            ) as f:
                json.dump(submission, f, indent=4)
        comm.synchronize()
        record = {}
        # fragment inference
        for idx, data_dict in enumerate(self.test_loader):
            end = time.time()
            data_dict = data_dict[0]  # current assume batch size is 1
            fragment_list = data_dict.pop("fragment_list")
            segment = data_dict.pop("segment")
            data_name = data_dict.pop("name")
            pred_save_path = os.path.join(save_path, "{}_pred.npy".format(data_name))
            if os.path.isfile(pred_save_path):
                logger.info(
                    "{}/{}: {}, loaded pred and label.".format(
                        idx + 1, len(self.test_loader), data_name
                    )
                )
                pred = np.load(pred_save_path)
            else:
                if not self.online:
                    self.model.load_state_dict(init_parameters, strict=True)
                    scaler = torch.cuda.amp.GradScaler() if self.cfg.enable_amp else None

                pred = torch.zeros((segment.size, self.cfg.data.num_classes)).cuda()
                update_fragments = []
                if self.num_updates_scene == 0:
                    update_fragments = [i for i in range(len(fragment_list))]
                else:
                    block_frag = len(fragment_list)//self.num_updates_scene
                    update_fragments = [i*block_frag for i in range(self.num_updates_scene)]
                for i in range(len(fragment_list)):
                    fragment_batch_size = 1
                    s_i, e_i = i * fragment_batch_size, min(
                        (i + 1) * fragment_batch_size, len(fragment_list)
                    )
                    input_dict = collate_fn(fragment_list[s_i:e_i])
                    for key in input_dict.keys():
                        if isinstance(input_dict[key], torch.Tensor):
                            input_dict[key] = input_dict[key].cuda(non_blocking=True)
                    idx_part = input_dict["index"]

                    # Start TTT-KD
                    if self.num_ttt_steps > 0 and i in update_fragments:
                        if not self.scene_online and not self.online:
                            self.model.load_state_dict(init_parameters, strict=True)
                            scaler = torch.cuda.amp.GradScaler() if self.cfg.enable_amp else None

                        self.model.ttt()
                        logger.info(">>>>> Start TTT")
                        for ttt_iter in range(self.num_ttt_steps):
                            with torch.cuda.amp.autocast(enabled=self.cfg.enable_amp):
                                loss = self.model(input_dict)["loss"]
                            if self.cfg.enable_amp:
                                scaler.scale(loss).backward()
                                scaler.step(optimizer)
                                scaler.update()
                            else:
                                loss.backward()
                                optimizer.step()
                            optimizer.zero_grad()
                            if ttt_iter%25 == 0:
                                logger.info(
                                    "Loss: {:.4f}, Iter: {:4d}/{:4d}".format(
                                        loss.item(), ttt_iter, self.num_ttt_steps))
                        self.model.eval()
                    # End TTT-KD
                        
                    with torch.no_grad():
                        pred_part = self.model(input_dict)["seg_logits"]  # (n, k)
                        pred_part = F.softmax(pred_part, -1)
                        if self.cfg.empty_cache:
                            torch.cuda.empty_cache()
                        bs = 0
                        for be in input_dict["offset"]:
                            pred[idx_part[bs:be], :] += pred_part[bs:be]
